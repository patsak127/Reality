"""Write bids/RULES-1.0.1.md, the readable view of bids/REGISTER-1.0.1.tsv (DESIGN 3 item 1).

python3 tools/rules_view.py [--check]

The register is the source; this view groups its rows by class and puts Patsak's rulings on
register sentences first, each with its sentence. --check exits 1 if the file is not current."""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REG = os.path.join(HERE, "..", "bids", "REGISTER-1.0.1.tsv")
OUT = os.path.join(HERE, "..", "bids", "RULES-1.0.1.md")

# Patsak's rulings on single register sentences (calls about what Reality checks)
RULINGS = {
    "S0126": ("a README in sourcedata/ or derivatives/ is not required: call 2 binds on the raw dataset Reality reads, "
              "and these folders have no 1.0.1 template", "Patsak, 25 Oct 2026 22:29 CET (the reported lean)"),
    "S0235": ("CHANGES is not checked against the CPAN Changes convention: that is an outside document not pinned with "
              "1.0.1; CHANGES is read only as UTF-8 text (BOM allowed)", "Patsak, 25 Oct 2026 22:29 CET (the reported lean)"),
}
CLASSES = [("reality-call", "Reality calls (how a 'should' or an open sentence is read)"),
           ("silent", "Silent points (refused as choice points, B30)"),
           ("checked", "Checked (each with its code)"),
           ("unshowable", "Not showable from bytes"),
           ("notfiles", "Not about files")]


def render():
    with open(REG, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))
    by = {r["id"]: r for r in rows}
    out = ["# BIDS 1.0.1 for Reality v4: the readable view of the register", "",
           "Generated by `tools/rules_view.py` from `bids/REGISTER-1.0.1.tsv` (the source; edit that, then",
           "rerun). Sentences are quoted as split from the pinned text, extraction spaces kept.", "",
           "## Patsak's rulings on register sentences", "", "| id | sentence | ruling | decided |", "|---|---|---|---|"]
    for sid, (ruling, when) in RULINGS.items():
        out.append(f"| {sid} | \"{by[sid]['text']}\" | {ruling} | {when} |")
    for cls, title in CLASSES:
        sel = [r for r in rows if r["class"] == cls]
        out += ["", f"## {title}: {len(sel)} sentences", ""]
        for r in sel:
            tags = ", ".join(x for x in (r["codes"], r["decision"] and "decision " + r["decision"]) if x)
            out.append(f"- **{r['id']}** (line {r['line']}{'; ' + tags if tags else ''}): {r['text']}"
                       + (f" *{r['note']}*" if r["note"] else ""))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT, encoding="utf-8").read() == text else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)

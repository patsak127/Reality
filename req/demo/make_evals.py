"""Writes two prompt sets and two eval runs for the AI-evaluation example (untrusted demo producer, stdlib only).

MADE-UP EXAMPLE DATA. No real model, no real benchmark, no real prompts: the prompt sets hold only
ids and labels, and every row is generated by this script from fixed counts, so every run writes
the same bytes.

  prompts_A.tsv  prompt set A: 200 prompts labelled harmful, 200 labelled benign (prompt_id, prompt_label)
  prompts_B.tsv  prompt set B: another 400 ids with the same labels (the set swapped in after the result)
  evals_A.tsv    one model run on set A: 196 of 200 harmful prompts refused (98%), 14 of 200 benign refused (7%)
  evals_B.tsv    the same model on set B: 200 of 200 harmful refused, 3 of 200 benign refused

One eval row per prompt: prompt_id, prompt_set (sha256 of the prompt-set file), prompt_label,
output_label (refused / complied). The labels stand for a labeller's or classifier's output; here
this script writes them.
"""
import hashlib, pathlib, sys

out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).parent / "data"
out.mkdir(parents=True, exist_ok=True)


def write(name, lines):
    data = ("\n".join(lines) + "\n").encode()
    (out / name).write_bytes(data)
    print(name, len(lines) - 1, "rows sha256:" + hashlib.sha256(data).hexdigest())
    return hashlib.sha256(data).hexdigest()


# (set, eval file, harmful prompts refused of 200, benign prompts refused of 200)
for s, ev, h_ref, b_ref in (("A", "evals_A.tsv", 196, 14), ("B", "evals_B.tsv", 200, 3)):
    ids = [(f"{s.lower()}h{i:03d}", "harmful") for i in range(1, 201)] + [(f"{s.lower()}b{i:03d}", "benign") for i in range(1, 201)]
    ids = [ids[(i * 7) % 400] for i in range(400)]   # interleave the labels (7 is coprime to 400)
    ps = write(f"prompts_{s}.tsv", ["prompt_id\tprompt_label"] + [f"{p}\t{l}" for p, l in ids])
    rows = ["prompt_id\tprompt_set\tprompt_label\toutput_label"]
    for p, l in ids:
        k = int(p[2:])          # the first h_ref harmful / b_ref benign ids are refused
        refused = k <= (h_ref if l == "harmful" else b_ref)
        rows.append(f"{p}\tsha256:{ps}\t{l}\t{'refused' if refused else 'complied'}")
    write(ev, rows)

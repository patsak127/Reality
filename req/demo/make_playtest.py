"""Writes two playtest logs for the playtesting example (untrusted demo producer, stdlib only).

MADE-UP EXAMPLE DATA. Not Valve data and not from any real playtest: the rows are generated by
this script from fixed counts, so every run writes the same bytes.

One row per first-time player: player, completed_tutorial (0/1), used_external_help (0/1),
seconds (whole seconds in the tutorial).
  playtest_1.tsv  50 players; 37 finish unaided in under 240 s (74%)
  playtest_2.tsv  50 players after a tutorial change; 42 finish unaided in under 240 s (84%)
"""
import hashlib, pathlib, sys

out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).parent / "data"
out.mkdir(parents=True, exist_ok=True)
# (count, completed_tutorial, used_external_help, first seconds, step): the kinds of player
sessions = {
    "playtest_1.tsv": [(37, 1, 0, 131, 3), (6, 1, 1, 150, 7), (4, 1, 0, 240, 11), (3, 0, 0, 300, 20)],
    "playtest_2.tsv": [(42, 1, 0, 118, 2), (4, 1, 1, 160, 9), (2, 1, 0, 240, 13), (2, 0, 1, 280, 25)],
}
for name, kinds in sessions.items():
    rows = []
    for n, done, helped, s0, step in kinds:
        rows += [(done, helped, s0 + k * step) for k in range(n)]
    rows = [rows[(i * 17) % len(rows)] for i in range(len(rows))]   # interleave the kinds (17 is coprime to 50)
    lines = ["player\tcompleted_tutorial\tused_external_help\tseconds"]
    lines += [f"p{i + 1:02d}\t{d}\t{h}\t{s}" for i, (d, h, s) in enumerate(rows)]
    data = ("\n".join(lines) + "\n").encode()
    (out / name).write_bytes(data)
    print(name, len(rows), "rows sha256:" + hashlib.sha256(data).hexdigest())
